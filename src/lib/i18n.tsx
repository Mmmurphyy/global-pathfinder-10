function toTraditional(text: string) {
  return Array.from(text, (character) => TRADITIONAL_CHARACTERS[character] ?? character).join("");
}

const STORAGE_KEY = "unipath-locale";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>("zh-CN");
  const [ready, setReady] = useState(false);

  useEffect(() => {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved === "zh-CN" || saved === "zh-TW" || saved === "en") setLocale(saved);
    setReady(true);
  }, []);

  useEffect(() => {
    if (!ready) return;
    window.localStorage.setItem(STORAGE_KEY, locale);
    document.documentElement.lang = locale;
  }, [locale, ready]);

  const value: I18nContextValue = {
    locale,
    setLocale,
    t: (text) =>
      locale === "en"
        ? (EN[text] ?? text)
        : locale === "zh-TW"
          ? (ZH_TW[text] ?? toTraditional(text))
          : text,
  };

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}
